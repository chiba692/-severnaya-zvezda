-- Push: один endpoint = одна подписка. Старые дубли удаляем безопасно.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null,
  subscription jsonb not null,
  created_at timestamptz not null default now()
);

do $$
begin
  if to_regclass('public.push_subscriptions') is not null then
    execute 'delete from public.push_subscriptions a using public.push_subscriptions b where a.ctid < b.ctid and a.endpoint = b.endpoint';
    execute 'create unique index if not exists push_subscriptions_endpoint_unique on public.push_subscriptions(endpoint)';
  end if;
end $$;
