alter table public.bookings add column if not exists updated_at timestamptz not null default now();

update public.bookings
set public_token = encode(gen_random_bytes(24), 'hex')
where public_token is null or public_token = '';

alter table public.bookings alter column public_token set default encode(gen_random_bytes(24), 'hex');
alter table public.bookings alter column public_token set not null;

create unique index if not exists bookings_public_token_unique on public.bookings(public_token);

-- Отменённые и отклонённые записи больше не удерживают слот.
drop index if exists bookings_date_time_unique;
create unique index bookings_date_time_unique
on public.bookings (booking_date, booking_time)
where service <> 'inpatient' and status not in ('rejected','cancelled');

alter table public.bookings drop constraint if exists bookings_status_check;
alter table public.bookings add constraint bookings_status_check
check (status in ('new','accepted','arrived','in_progress','completed','rejected','no_show','cancelled'));

-- Отзывы после завершённого визита. Публикуются только после подтверждения администратора.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  display_name text not null,
  text text not null,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index if not exists reviews_booking_unique on public.reviews(booking_id);

